import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {mkdtemp, readFile, rm, writeFile} from "node:fs/promises";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {test} from "node:test";
import {pathToFileURL} from "node:url";
import {launchBrowser, root} from "./desk.mjs";

test("the standalone replay executes the signed review with networking disabled", {timeout:60000}, async t => {
  const directory = await mkdtemp(join(tmpdir(), "morph-offline-replay-"));
  t.after(() => rm(directory, {recursive:true, force:true}));
  const file = join(directory, "Change review.html");
  const python = process.env.MORPH_PYTHON || (process.platform === "win32" ? "python" : "python3");
  execFileSync(python, ["scripts/replay/build.py", file], {cwd:root});
  const browser = await launchBrowser();
  t.after(() => browser.close());
  const context = await browser.newContext({offline:true});
  const page = await context.newPage();
  const errors = [], requests = [];
  page.on("pageerror", err => errors.push(err.message));
  page.on("request", req => { if (/^(https?|wss?):/.test(req.url())) requests.push(req.url()); });
  page.on("websocket", socket => requests.push(socket.url()));
  await page.goto(pathToFileURL(file).href);
  await page.locator("#tab-checks").click();
  const timeOrigin = await page.evaluate(() => performance.timeOrigin);
  assert.match(await page.locator("#stage").textContent(), /Signed release 1/);
  assert.equal(await page.locator("#comparison").isVisible(), false);
  await page.locator("#advance").click();
  await page.getByText("Signed release 2", {exact:false}).waitFor();
  assert.match(await page.locator("#facts").textContent(), /Server compare replyallowed/);
  assert.equal(await page.locator("#tab-checks").getAttribute("aria-pressed"), "true");
  await page.locator("#show").click();
  await page.locator("#observation").waitFor();
  assert.equal(await page.locator("#cases tr").count(), 6);
  assert.equal(await page.locator("#cases .fixed").count(), 4);
  if (process.env.MORPH_REPLAY_SCREENSHOT) await page.screenshot({path:process.env.MORPH_REPLAY_SCREENSHOT});
  await page.locator("#advance").click();
  await page.getByText("Signed release 3", {exact:false}).waitFor();
  assert.match(await page.locator("#facts").textContent(), /Server compare replyrefused/);
  assert.equal(await page.locator("#comparison").isVisible(), false);
  assert.equal(await page.locator("#tab-checks").getAttribute("aria-pressed"), "true");
  await page.locator("#advance").click();
  await page.getByText("Signed release 1", {exact:false}).waitFor();
  assert.equal(await page.evaluate(() => performance.timeOrigin), timeOrigin);
  assert.deepEqual(errors, []);
  assert.deepEqual(requests, []);

  const html = await readFile(file, "utf8");
  const altered = html.replace('"x-morph-release":"compare"', '"x-morph-release":"altered"');
  assert.notEqual(altered, html);
  const modified = join(directory, "altered.html");
  await writeFile(modified, altered);
  await page.goto(pathToFileURL(modified).href);
  await page.getByText("Signed release 1", {exact:false}).waitFor();
  await page.locator("#advance").click();
  await page.getByText("Replay stopped").waitFor();
  assert.match(await page.locator("#error").textContent(), /signature/);
  assert.equal(await page.locator("#comparison").isVisible(), false);
});
